namespace SkyMessage.Contracts;

public sealed record DeviceInfoDto
{
    public string DeviceName { get; init; } = "";
    public ClientPlatform Platform { get; init; }
    public string AppVersion { get; init; } = "";
    public string? OsVersion { get; init; }
}

public enum RegistrationMode
{
    Open = 0,
    /// <summary>Requires <see cref="RegisterRequest.InviteCode"/> matching the server's code.</summary>
    InviteCode = 1,
    Closed = 2,
}

public sealed record RegisterRequest
{
    public string Username { get; init; } = "";
    public string Password { get; init; } = "";
    public string DisplayName { get; init; } = "";
    public DeviceInfoDto Device { get; init; } = new();
    /// <summary>Only when the server runs in <see cref="RegistrationMode.InviteCode"/>.</summary>
    public string? InviteCode { get; init; }
}

public sealed record LoginRequest
{
    /// <summary>Username (case-insensitive, optional leading '@') or a linked phone number.</summary>
    public string Login { get; init; } = "";
    public string Password { get; init; } = "";
    public DeviceInfoDto Device { get; init; } = new();
    /// <summary>ISO 3166 alpha-2 region used to parse a phone login without '+' (e.g. "TH", "RU").</summary>
    public string? DefaultRegion { get; init; }
}

public sealed record RefreshRequest
{
    public string RefreshToken { get; init; } = "";
}

public sealed record AuthResponse
{
    public Guid SessionId { get; init; }
    public string AccessToken { get; init; } = "";
    public DateTimeOffset AccessTokenExpiresAt { get; init; }
    public string RefreshToken { get; init; } = "";
    public DateTimeOffset RefreshTokenExpiresAt { get; init; }
    /// <summary>
    /// Per-session secret (base64url, 32 bytes) used to sign media URLs: the client appends
    /// <c>?t=</c><see cref="MediaSignature.Create"/>(key, sessionId, mediaId) so &lt;img&gt;/&lt;video&gt;
    /// can load content without an Authorization header. A leaked URL exposes one file and dies with
    /// the session. Returned on login, register and refresh (same value for the session's lifetime).
    /// </summary>
    public string MediaKey { get; init; } = "";
    public MeDto User { get; init; } = new();
}

public sealed record ChangePasswordRequest
{
    public string CurrentPassword { get; init; } = "";
    public string NewPassword { get; init; } = "";
    public bool TerminateOtherSessions { get; init; } = true;
}

public sealed record DeleteAccountRequest
{
    public string Password { get; init; } = "";
}

public sealed record UsernameAvailabilityDto
{
    public string Username { get; init; } = "";
    public bool Available { get; init; }
    /// <summary><see cref="ErrorCodes.UsernameInvalid"/> or <see cref="ErrorCodes.UsernameTaken"/> when not available.</summary>
    public string? ErrorCode { get; init; }
}

public sealed record SessionDto
{
    public Guid Id { get; init; }
    public string DeviceName { get; init; } = "";
    public ClientPlatform Platform { get; init; }
    public string AppVersion { get; init; } = "";
    public string? OsVersion { get; init; }
    public string? IpAddress { get; init; }
    public DateTimeOffset CreatedAt { get; init; }
    public DateTimeOffset LastActiveAt { get; init; }
    public bool IsCurrent { get; init; }
}

public sealed record RegisterPushRequest
{
    public PushProvider Provider { get; init; }
    public string Token { get; init; } = "";
    /// <summary>Base64 AES-256 key generated by the device; the server encrypts push payloads with it.</summary>
    public string? EncryptionKey { get; init; }
}

public sealed record ServerInfoDto
{
    /// <summary>
    /// Stable id of this deployment (generated once, stored in the database). Clients only fail over to
    /// addresses reporting the same id; a different id means a different server (sign out first).
    /// </summary>
    public Guid InstanceId { get; init; }
    public string Name { get; init; } = "SkyMessage";
    public string Version { get; init; } = "";
    public int ApiVersion { get; init; } = 1;
    /// <summary>Oldest client version this server supports; older apps should ask the user to update.</summary>
    public string? MinClientVersion { get; init; }
    /// <summary>Public https base for shareable profile/invite links (null = use the address in use).</summary>
    public string? PublicBaseUrl { get; init; }
    public RegistrationMode RegistrationMode { get; init; }
    public long MaxUploadBytes { get; init; }
    public int ChunkSize { get; init; }
    public bool CallsEnabled { get; init; }
    public DateTimeOffset ServerTime { get; init; }
    public IReadOnlyList<string> Features { get; init; } = [];
    /// <summary>
    /// Other addresses of this same deployment (mirrors / relays). Clients remember them per InstanceId and
    /// fail over to them when the current address is blocked — after verifying <see cref="ServerProofDto"/>.
    /// </summary>
    public IReadOnlyList<string> MirrorUrls { get; init; } = [];
}

/// <summary>
/// GET api/server/proof?sid=&amp;nonce= — proves that an address really is the client's server before
/// tokens are sent to it: Proof = <see cref="MediaSignature.CreateProof"/>(session media key, nonce, host).
/// An impostor copying InstanceId cannot produce it.
/// </summary>
public sealed record ServerProofDto
{
    public Guid InstanceId { get; init; }
    public string Proof { get; init; } = "";
}
